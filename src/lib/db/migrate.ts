// Applies pending SQL migrations from ./drizzle to the database pointed at
// by DATABASE_URL. Run with `npm run db:migrate`.
//
// This is a plain script (not the Next.js app) so it can run in CI/CD or a
// deploy hook before the app starts.
import "dotenv/config";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import { Pool } from "pg";

async function main() {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const db = drizzle(pool);

  console.log("Running migrations...");
  await migrate(db, { migrationsFolder: "./drizzle" });
  console.log("Migrations complete.");

  await pool.end();
}

main().catch((err) => {
  console.error("Migration failed:", err);
  process.exit(1);
});
